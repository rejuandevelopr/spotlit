// Typed Firestore paths. One place to change the data layout.
export const P = {
  user: (uid: string) => `users/${uid}`,
  notifications: (uid: string) => `users/${uid}/notifications`,
  notification: (uid: string, id: string) => `users/${uid}/notifications/${id}`,
  slug: (slug: string) => `slugs/${slug}`,
  venues: () => `venues`,
  venue: (id: string) => `venues/${id}`,
  cards: (venueId: string) => `venues/${venueId}/cards`,
  card: (venueId: string, version: number) => `venues/${venueId}/cards/${String(version).padStart(4, "0")}`,
  taste: (venueId: string) => `venues/${venueId}/taste/profile`,
  rivals: (venueId: string) => `venues/${venueId}/rivals`,
  rival: (venueId: string, rivalId: string) => `venues/${venueId}/rivals/${rivalId}`,
  actions: (venueId: string) => `venues/${venueId}/actions`,
  action: (venueId: string, id: string) => `venues/${venueId}/actions/${id}`,
  inbox: (venueId: string) => `venues/${venueId}/inbox`,
  inboxItem: (venueId: string, id: string) => `venues/${venueId}/inbox/${id}`,
  segments: () => `segments`,
  segment: (key: string) => `segments/${key}`,
  runs: () => `runs`,
  run: (id: string) => `runs/${id}`,
  rounds: (runId: string) => `runs/${runId}/rounds`,
  round: (runId: string, personaId: string) => `runs/${runId}/rounds/${personaId}`,
  messages: (runId: string) => `runs/${runId}/messages`,
  message: (runId: string, id: string) => `runs/${runId}/messages/${id}`,
  share: (token: string) => `shares/${token}`,
  qlooCache: (hash: string) => `qlooCache/${hash}`,
  qlooCalls: () => `qlooCalls`,
  qlooCall: (id: string) => `qlooCalls/${id}`,
  llmCache: (hash: string) => `llmCache/${hash}`,
  rateLimit: (key: string) => `rateLimits/${key}`,
  meta: (key: string) => `meta/${key}`,
};
